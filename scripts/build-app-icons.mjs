/**
 * Generates `packages/ui/src/icons/brand-icons.generated.tsx` from the brand icons
 * (`docs/brand/icons`). Icons are inline JSX `<svg>` so stylesheet rules for `svg` apply.
 * Run after changing the drawings:
 *
 *   node scripts/build-app-icons.mjs && pnpm lint:fix
 */

import { writeFileSync } from 'node:fs';
import { glassSvg } from '../docs/brand/icons/glass.mjs';
import { ICONS, NAMES } from '../docs/brand/icons/icons.mjs';

const camel = (name) =>
  name.startsWith('data-') ? name : name.replace(/-(\w)/g, (_, c) => c.toUpperCase());

/** Converts the glass SVG markup to JSX. Handles only the few tags and attributes it uses. */
function jsx(markup) {
  const out = [];
  const tag = /<(\/?)([A-Za-z][\w]*)((?:\s+[\w:-]+(?:="[^"]*")?)*)\s*(\/?)>/g;
  for (const [, closing, name, attributes, selfClosing] of markup.matchAll(tag)) {
    if (closing) {
      out.push(`</${name}>`);
      continue;
    }
    const props = [...attributes.matchAll(/([\w:-]+)(?:="([^"]*)")?/g)].map(([, key, value]) => {
      if (value === undefined) return camel(key);
      if (key === 'style') {
        const [property, setting] = value.split(':');
        return `style={{ ${property.trim()}: ${JSON.stringify(setting.trim())} }}`;
      }
      if (key === 'xmlns') return '';
      return `${camel(key)}=${JSON.stringify(value)}`;
    });
    if (name === 'svg') props.push('aria-hidden="true"', 'focusable="false"');
    out.push(`<${name} ${props.filter(Boolean).join(' ')}${selfClosing ? ' /' : ''}>`);
  }
  return out.join('');
}

const icons = Object.entries(ICONS).map(
  ([key, inner]) =>
    `  ${JSON.stringify(key)}: () => ${jsx(glassSvg(inner, { id: `bi-${key}`, size: 20 }))},`,
);
const names = Object.entries(NAMES).map(
  ([key, name]) => `  ${JSON.stringify(key)}: ${JSON.stringify(name)},`,
);

writeFileSync(
  new URL('../packages/ui/src/icons/brand-icons.generated.tsx', import.meta.url),
  `/**
 * Generated by scripts/build-app-icons.mjs from docs/brand/icons. Do not edit.
 * Each icon is a 16-unit SVG drawn as glass in the text colour (\`currentColor\`).
 */

import type { ReactElement } from 'react';

export const BRAND_ICONS = {
${icons.join('\n')}
} satisfies Record<string, () => ReactElement>;

export type BrandIconKey = keyof typeof BRAND_ICONS;

/** What each icon is called in the interface. */
export const BRAND_ICON_NAMES: Record<BrandIconKey, string> = {
${names.join('\n')}
};
`,
);
console.log(Object.keys(ICONS).length, 'icons');
