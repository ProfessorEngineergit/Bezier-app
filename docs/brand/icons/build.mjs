/**
 * Writes `bezier-icons.css`: every icon as a mask, so `<i class="bi bi-extrude"></i>` takes the
 * colour of the text around it and any size. Run `node docs/brand/icons/build.mjs` after changing
 * `icons.mjs`. The CSS is committed so a page needs no build step.
 *
 * A mask carries only alpha. It keeps the glass's fade and its frosted surfaces, but not the white
 * line of light or the shadow: the light is left out here, and the shadow is a CSS drop-shadow on
 * the element. For the full glass, draw the SVG inline with `glassSvg` from `glass.mjs`.
 */

import { writeFileSync } from 'node:fs';
import { glassSvg } from './glass.mjs';
import { ICONS } from './icons.mjs';

const here = new URL('.', import.meta.url).pathname;

const maskSvg = (inner) =>
  glassSvg(inner, { id: 'm' })
    .replace(/<g stroke="#fff"[\s\S]*?<\/g>\n/, '')
    .replace(' filter="url(#m-sh)"', '')
    .replaceAll('currentColor', '#000');

const rules = Object.entries(ICONS)
  .map(
    ([key, inner]) =>
      `.bi-${key} { --bi: url("data:image/svg+xml,${encodeURIComponent(maskSvg(inner))}"); }`,
  )
  .join('\n');

writeFileSync(
  `${here}bezier-icons.css`,
  `/*
 * Generated by docs/brand/icons/build.mjs. Do not edit.
 *
 * <i class="bi bi-extrude"></i>. Each icon is a mask, so it takes the colour of the text around it
 * and any size (font-size, or width and height).
 */
.bi {
  display: inline-block;
  width: 1.25em;
  height: 1.25em;
  flex: none;
  vertical-align: -0.2em;
  background: currentcolor;
  -webkit-mask: var(--bi) center / contain no-repeat;
  mask: var(--bi) center / contain no-repeat;
  filter: drop-shadow(0 0.04em 0.05em rgb(11 18 32 / 22%));
}
${rules}
`,
);
console.log(Object.keys(ICONS).length, 'icons');
